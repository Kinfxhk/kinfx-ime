#!/usr/bin/env python3
"""Build lexicon/hk/kinfx_assoc.dict.yaml: Windows-style association phrases 聯想.

After a single Chinese character is picked, KINFX shows follow-up words whose
first character is the picked one (我 → 們 國 方 …). Windows shows the suffix
only; picking it appends to the already-committed character.

Source words: essay-cantonese.txt (rime-cantonese, CC BY 4.0). For each first
character that also exists in schemas/kinfx-quick/ms_quick_order.tsv, keep the
top --max words (2–4 chars, by essay frequency) and write their suffix with a
code derived from the first character's code point: hex digits 0–f are mapped
to a–p (我 U+6211 → gcbb). The schema kinfx_assoc.schema.yaml is dependency-only
and compiles this into a native table for kinfx_quick.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = "0.5.0"


def encode_char(ch: str) -> str:
    return "".join(chr(ord("a") + int(d, 16)) for d in format(ord(ch), "x"))


def is_basic_cjk(ch: str) -> bool:
    o = ord(ch)
    return (
        0x3400 <= o <= 0x4DBF
        or 0x4E00 <= o <= 0x9FFF
        or 0xF900 <= o <= 0xFAFF
        or 0x20000 <= o <= 0x3134F
    )


def load_ms_chars(path: Path) -> set[str]:
    out: set[str] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        code, _, chars = line.partition("\t")
        if len(code) != 2:
            continue
        for ch in chars.split(" "):
            if ch:
                out.add(ch)
    return out


def load_assoc_words(path: Path) -> dict[str, list[tuple[str, int]]]:
    """first-char -> [(word, weight)] for 2-4 char CJK words, weight descending."""
    groups: dict[str, dict[str, int]] = defaultdict(dict)
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.rstrip("\r\n").split("\t")
        if len(parts) < 2 or not parts[1].isdigit():
            continue
        word, weight = parts[0], int(parts[1])
        if not (2 <= len(word) <= 4):
            continue
        if not all(is_basic_cjk(ch) for ch in word):
            continue
        groups[word[0]][word] = max(groups[word[0]].get(word, 0), weight)
    return {k: sorted(v.items(), key=lambda kv: -kv[1]) for k, v in groups.items()}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--essay-cantonese", type=Path, required=True)
    ap.add_argument("--ms-order", type=Path, default=ROOT / "schemas/kinfx-quick/ms_quick_order.tsv")
    ap.add_argument("--max", type=int, default=36)
    ap.add_argument("--out", type=Path, default=ROOT / "lexicon/hk/kinfx_assoc.dict.yaml")
    args = ap.parse_args()

    ms_chars = load_ms_chars(args.ms_order)
    groups = load_assoc_words(args.essay_cantonese)
    rows: list[tuple[str, str, int]] = []
    nchars = 0
    for head, words in sorted(groups.items()):
        if head not in ms_chars:
            continue
        nchars += 1
        code = encode_char(head)
        for word, weight in words[: args.max]:
            rows.append((word[1:], code, weight))

    header = (
        "# encoding: utf-8\n"
        "# Generated by scripts/gen_assoc.py — do not hand-edit.\n"
        "# Windows-style association suffixes: text = suffix, code = first char's\n"
        "# code point (hex 0-f → a-p). Source words: essay-cantonese.txt\n"
        "# (rime-cantonese, CC BY 4.0). See lexicon/NOTICE.\n"
        f"# Chars: {nchars}; rows: {len(rows)}.\n"
        "\n"
        "---\n"
        f'name: kinfx_assoc\nversion: "{VERSION}"\nsort: by_weight\n'
        "use_preset_vocabulary: false\n"
        "columns:\n  - text\n  - code\n  - weight\n...\n\n"
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(header)
        for text, code, weight in rows:
            fh.write(f"{text}\t{code}\t{weight}\n")
    print(f"wrote {args.out}: {nchars} chars, {len(rows)} suffixes (max {args.max}/char)")


if __name__ == "__main__":
    main()
