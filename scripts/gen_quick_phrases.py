#!/usr/bin/env python3
"""Build lexicon-driven Sucheng phrase codes and the English completion dict.

Phrase codes are the concatenation of each character's single best quick code
(highest weight in kinfx_quick.dict.yaml). Words come only from the lexicon.
A character with several codes does not fan out: there is no of×c* product.

Outputs (licenses: lexicon/NOTICE, not MIT):
  lexicon/hk/kinfx_hk_words.dict.yaml
  lexicon/hk/kinfx_hk_idioms.dict.yaml
  lexicon/hk/kinfx_quick_phrase.dict.yaml
  lexicon/en/kinfx_en.dict.yaml
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Spoken-corpus floors. 4-character entries are the idiom/chengyu band and
# use a lower floor so set phrases survive. 無錯 (essay-cantonese ~19399) is
# well above the 2-character floor.
MIN_WEIGHT = {2: 400, 3: 250, 4: 40, 5: 120}
MIN_CODE_LEN = 4
MAX_WORD_LEN = 5
VERSION = "0.3.1"

# English completion. SCOWL has no Gmail, scriptwriting, or voiceover;
# extras supply those acceptance forms.
EN_BASE_WEIGHT = 100
EN_MIN_LEN = 2
EN_MAX_LEN = 16

WORD_RE = re.compile(r"[A-Za-z]{2,16}")
CODE_RE = re.compile(r"[a-z]+")


def load_best_codes(path: Path) -> dict[str, str]:
    """char -> one quick code. Highest weight, then longer code, then alpha."""
    best: dict[str, tuple[int, int, str]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#") or "\t" not in line:
            continue
        parts = line.split("\t")
        if len(parts) < 3 or len(parts[0]) != 1:
            continue
        text, code = parts[0], parts[1]
        if not CODE_RE.fullmatch(code):
            continue
        try:
            weight = int(float(parts[2]))
        except ValueError:
            continue
        cand = (weight, len(code), code)
        prev = best.get(text)
        if prev is None or cand > prev:
            best[text] = cand
    return {ch: code for ch, (_w, _n, code) in best.items()}


def encode_word(word: str, codes: dict[str, str]) -> str | None:
    """One code per word. Missing glyph or a too-short code → skip."""
    parts: list[str] = []
    for ch in word:
        code = codes.get(ch)
        if not code:
            return None
        parts.append(code)
    full = "".join(parts)
    if len(full) < MIN_CODE_LEN or not CODE_RE.fullmatch(full):
        return None
    return full


def _is_basic_cjk(word: str) -> bool:
    return all(0x4E00 <= ord(ch) <= 0x9FFF for ch in word)


def load_essay_words(path: Path) -> dict[str, int]:
    """word -> max weight. Single characters are not phrases."""
    out: dict[str, int] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#") or "\t" not in line:
            continue
        word, raw = line.split("\t", 1)
        n = len(word)
        if n < 2 or n > MAX_WORD_LEN or not _is_basic_cjk(word):
            continue
        try:
            weight = int(float(raw.split("\t", 1)[0]))
        except ValueError:
            continue
        if weight > out.get(word, 0):
            out[word] = weight
    return out


def build_phrase_rows(
    words: dict[str, int],
    codes: dict[str, str],
) -> tuple[list[tuple[str, str, int]], list[tuple[str, str, int]]]:
    """Return (hk_words, hk_idioms). Idioms are the 4-character band."""
    hk_words: list[tuple[str, str, int]] = []
    hk_idioms: list[tuple[str, str, int]] = []
    for word, weight in words.items():
        floor = MIN_WEIGHT.get(len(word))
        if floor is None or weight < floor:
            continue
        code = encode_word(word, codes)
        if code is None:
            continue
        row = (word, code, weight)
        if len(word) == 4:
            hk_idioms.append(row)
        else:
            hk_words.append(row)
    hk_words.sort(key=lambda r: (r[1], -r[2], r[0]))
    hk_idioms.sort(key=lambda r: (r[1], -r[2], r[0]))
    return hk_words, hk_idioms


def _dict_header(name: str, blurb: str) -> str:
    return f"""# encoding: utf-8
# Generated by scripts/gen_quick_phrases.py — do not hand-edit.
# {blurb}
# License: see lexicon/NOTICE. This file is not MIT.

---
name: {name}
version: "{VERSION}"
sort: by_weight
use_preset_vocabulary: false
columns:
  - text
  - code
  - weight
...

"""


def write_table(path: Path, name: str, blurb: str, rows: list[tuple[str, str, int]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        fh.write(_dict_header(name, blurb))
        for text, code, weight in rows:
            fh.write(f"{text}\t{code}\t{weight}\n")


def write_phrase_master(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"""# encoding: utf-8
# Generated by scripts/gen_quick_phrases.py — do not hand-edit.
# Imports HK words + 4-character idiom band. No preset vocabulary
# (that would cartesian-encode essay.txt). License: lexicon/NOTICE.

---
name: kinfx_quick_phrase
version: "{VERSION}"
sort: by_weight
use_preset_vocabulary: false
import_tables:
  - kinfx_hk_words
  - kinfx_hk_idioms
...
""",
        encoding="utf-8",
    )


def _case_score(word: str) -> int:
    if word.islower():
        return 3
    if word.istitle():
        return 2
    if word.isupper():
        return 1
    return 0


def load_scowl(path: Path) -> dict[str, str]:
    """lowercase code -> one display form (prefer ordinary lowercase)."""
    chosen: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        word = line.strip()
        if not WORD_RE.fullmatch(word):
            continue
        if not (EN_MIN_LEN <= len(word) <= EN_MAX_LEN):
            continue
        code = word.lower()
        prev = chosen.get(code)
        if prev is None or _case_score(word) > _case_score(prev):
            chosen[code] = word
    return chosen


def load_extras(path: Path) -> list[tuple[str, str, int]]:
    rows: list[tuple[str, str, int]] = []
    if not path.exists():
        return rows
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        text, code = parts[0], parts[1].lower()
        if not CODE_RE.fullmatch(code) or not text:
            continue
        weight = EN_BASE_WEIGHT
        if len(parts) >= 3:
            weight = int(float(parts[2]))
        rows.append((text, code, weight))
    return rows


def build_english_rows(
    scowl: dict[str, str],
    extras: list[tuple[str, str, int]],
) -> list[tuple[str, str, int]]:
    """SCOWL forms at a flat weight, then extras at their own weights."""
    by_key: dict[tuple[str, str], int] = {}
    for code, text in scowl.items():
        by_key[(text, code)] = EN_BASE_WEIGHT
    for text, code, weight in extras:
        key = (text, code)
        by_key[key] = max(by_key.get(key, 0), weight)
    rows = [(text, code, weight) for (text, code), weight in by_key.items()]
    rows.sort(key=lambda r: (r[1], -r[2], r[0]))
    return rows


def prefix_hits(
    rows: list[tuple[str, str, int]],
    prefix: str,
) -> list[tuple[str, str, int]]:
    """Same order the runtime uses: exact, then shorter remainder, then weight."""
    hits = [row for row in rows if row[1].startswith(prefix)]
    hits.sort(
        key=lambda row: (
            0 if row[1] == prefix else 1,
            len(row[1]) - len(prefix),
            -row[2],
            row[0],
        )
    )
    return hits


def _rank(rows: list[tuple[str, str, int]], prefix: str, text: str) -> tuple[int, int]:
    hits = prefix_hits(rows, prefix)
    for i, row in enumerate(hits, 1):
        if row[0] == text:
            return i, len(hits)
    return -1, len(hits)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--quick",
        type=Path,
        default=ROOT / "schemas/kinfx-quick/kinfx_quick.dict.yaml",
    )
    parser.add_argument(
        "--essay-cantonese",
        type=Path,
        default=Path("/usr/share/rime-data/essay-cantonese.txt"),
    )
    parser.add_argument(
        "--words-out",
        type=Path,
        default=ROOT / "lexicon/hk/kinfx_hk_words.dict.yaml",
    )
    parser.add_argument(
        "--idioms-out",
        type=Path,
        default=ROOT / "lexicon/hk/kinfx_hk_idioms.dict.yaml",
    )
    parser.add_argument(
        "--phrase-out",
        type=Path,
        default=ROOT / "lexicon/hk/kinfx_quick_phrase.dict.yaml",
    )
    parser.add_argument(
        "--en-words",
        type=Path,
        default=Path("/usr/share/dict/words"),
    )
    parser.add_argument(
        "--en-extras",
        type=Path,
        default=ROOT / "lexicon/en/extras.tsv",
    )
    parser.add_argument(
        "--en-out",
        type=Path,
        default=ROOT / "lexicon/en/kinfx_en.dict.yaml",
    )
    args = parser.parse_args()

    if not args.quick.exists():
        raise SystemExit(f"missing quick dict {args.quick}")
    if not args.essay_cantonese.exists():
        raise SystemExit(f"missing essay-cantonese {args.essay_cantonese}")

    codes = load_best_codes(args.quick)
    words = load_essay_words(args.essay_cantonese)
    hk_words, hk_idioms = build_phrase_rows(words, codes)
    combined = hk_words + hk_idioms

    ofc_rank, ofc_n = _rank(combined, "ofc", "無錯")
    ofca_rank, ofca_n = _rank(combined, "ofca", "無錯")
    if ofc_rank < 1 or ofca_rank < 1:
        raise SystemExit(
            f"無錯 missing after encode (ofc rank {ofc_rank}, ofca rank {ofca_rank})"
        )
    wucuo = next(row for row in combined if row[0] == "無錯")
    if wucuo[1] != "ofca":
        raise SystemExit(f"無錯 code {wucuo[1]}, want ofca")

    write_table(
        args.words_out,
        "kinfx_hk_words",
        "HK words (2/3/5-char) from essay-cantonese (CC BY 4.0). "
        "One Sucheng code each, derived from kinfx_quick (LGPL-3.0 cangjie/quick). "
        f"{len(hk_words)} entries. See lexicon/NOTICE.",
        hk_words,
    )
    write_table(
        args.idioms_out,
        "kinfx_hk_idioms",
        "4-character band from essay-cantonese (CC BY 4.0): chengyu and other set phrases. "
        "One Sucheng code each (LGPL-3.0 code mapping). "
        f"{len(hk_idioms)} entries. See lexicon/NOTICE.",
        hk_idioms,
    )
    write_phrase_master(args.phrase_out)

    en_rows: list[tuple[str, str, int]] = []
    if args.en_words.exists():
        scowl = load_scowl(args.en_words)
        extras = load_extras(args.en_extras)
        en_rows = build_english_rows(scowl, extras)
        write_table(
            args.en_out,
            "kinfx_en",
            "English completion. Word list Copyright 2000-2011 Kevin Atkinson (SCOWL). "
            "Permission to use, copy, modify, distribute and sell this word list for any "
            "purpose is granted without fee, provided this copyright notice appears in all "
            "copies. Project extras (Gmail/GMAIL, scriptwriting, voiceover) "
            "are added in lexicon/en/extras.tsv. "
            f"{len(en_rows)} entries. See lexicon/NOTICE.",
            en_rows,
        )
    else:
        print(f"skip english: missing {args.en_words}")

    gmai = prefix_hits(en_rows, "gmai")[:5] if en_rows else []
    scriptwriti = prefix_hits(en_rows, "scriptwriti")[:3] if en_rows else []
    voiceove = prefix_hits(en_rows, "voiceove")[:3] if en_rows else []
    print(
        f"codes={len(codes)} essay_words={len(words)} "
        f"hk_words={len(hk_words)} idioms={len(hk_idioms)}"
    )
    print(f"無錯 code={wucuo[1]} weight={wucuo[2]} ofc_rank={ofc_rank}/{ofc_n} ofca_rank={ofca_rank}/{ofca_n}")
    print("ofc top:", [f"{t}:{c}:{w}" for t, c, w in prefix_hits(combined, "ofc")[:8]])
    print("ofca top:", [f"{t}:{c}:{w}" for t, c, w in prefix_hits(combined, "ofca")[:5]])
    print("gmai top:", [f"{t}:{c}:{w}" for t, c, w in gmai])
    print("scriptwriti top:", [f"{t}:{c}:{w}" for t, c, w in scriptwriti])
    print("voiceove top:", [f"{t}:{c}:{w}" for t, c, w in voiceove])
    print(f"wrote {args.words_out.name}, {args.idioms_out.name}, {args.phrase_out.name}")


if __name__ == "__main__":
    main()
