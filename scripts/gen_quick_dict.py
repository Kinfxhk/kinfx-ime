#!/usr/bin/env python3
"""Generate kinfx_quick.dict.yaml (Sucheng = Cangjie first+last) from open cangjie tables."""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load_entries(path: Path) -> list[tuple[str, str]]:
    text = path.read_text(encoding="utf-8")
    body = text.split("...", 1)[1] if "..." in text else text
    out: list[tuple[str, str]] = []
    for line in body.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        char, code = parts[0], parts[1]
        if len(char) != 1:
            continue
        base = code.split("'")[0]
        if not base or not re.fullmatch(r"[a-z]+", base):
            continue
        q = base if len(base) == 1 else base[0] + base[-1]
        out.append((char, q))
    return out


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument(
        "--cangjie",
        type=Path,
        default=Path("/usr/share/rime-data/cangjie5.dict.yaml"),
    )
    p.add_argument(
        "--supplement",
        type=Path,
        default=ROOT / "third_party/rime-quick/quick5.supplement.dict.yaml",
    )
    p.add_argument(
        "--out",
        type=Path,
        default=ROOT / "schemas/kinfx-quick/kinfx_quick.dict.yaml",
    )
    args = p.parse_args()

    seen: set[tuple[str, str]] = set()
    rows: list[tuple[str, str]] = []
    for src in (args.cangjie, args.supplement):
        if not src.exists():
            print(f"skip missing {src}")
            continue
        for char, q in load_entries(src):
            key = (char, q)
            if key in seen:
                continue
            seen.add(key)
            rows.append((char, q))

    header = """# encoding: utf-8
# Generated by scripts/gen_quick_dict.py — Sucheng/Quick = Cangjie first+last.
# Licenses: see NOTICE and third_party/rime-quick/LICENSE (LGPL-3.0 upstream).

---
name: kinfx_quick
version: "0.1.0"
sort: by_weight
use_preset_vocabulary: true
columns:
  - text
  - code
...

"""
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8") as f:
        f.write(header)
        for char, q in rows:
            f.write(f"{char}\t{q}\n")
    print(f"wrote {args.out} ({len(rows)} entries)")


if __name__ == "__main__":
    main()
