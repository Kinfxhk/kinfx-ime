#!/usr/bin/env python3
"""Export kinfx_quick.dict.yaml to an OpenVanilla-style .cin code table.

One-way static table: each dictionary row becomes a `%chardef` line
(`code character`). The file has `%gen_inp`, `%keyname`, and `%chardef`
so someone can import it into OpenVanilla and edit the table there.

This is the character table only. Mixed English/Chinese input, Lua, and
association words stay in the Rime schema and are not written out.
The English name is KINFX-Quick, separate from OpenVanilla's Simplex table.

Dictionary rows keep the licences in NOTICE (rime-quick, rime-cangjie,
and rime-essay are LGPL-3.0). This script is original project code (MIT).
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DICT = ROOT / "schemas/kinfx-quick/kinfx_quick.dict.yaml"
DEFAULT_OUT = ROOT / "exports/kinfx_quick.cin"

# Cangjie / Sucheng radical names on a-z, same 26 lines as OpenVanilla
# DataTables/simplex.cin `%keyname`. The names are the standard keyboard
# labels; they are not OpenVanilla's character table.
KEYNAME_BLOCK = """\
a 日
b 月
c 金
d 木
e 水
f 火
g 土
h 竹
i 戈
j 十
k 大
l 中
m 一
n 弓
o 人
p 心
q 手
r 口
s 尸
t 廿
u 山
v 女
w 田
x 難
y 卜
z 重
"""

CODE_RE = re.compile(r"^[a-z]+$")
VERSION_RE = re.compile(r'(?m)^version:\s*"([^"]*)"')


def keyname_lines() -> list[str]:
    lines = KEYNAME_BLOCK.splitlines()
    letters = []
    for line in lines:
        key, sep, name = line.partition(" ")
        if sep != " " or not name or " " in name:
            raise SystemExit(f"bad keyname line: {line!r}")
        letters.append(key)
    if letters != list("abcdefghijklmnopqrstuvwxyz"):
        raise SystemExit("keyname block must be a-z in order")
    return lines


def parse_quick_dict(text: str) -> tuple[str, list[tuple[str, str]]]:
    """Return (version, rows of (text, code)) from a Rime dict.yaml string."""
    if "\n...\n" not in text:
        raise SystemExit("dict yaml has no '...' body separator")
    header, body = text.split("\n...\n", 1)
    version_match = VERSION_RE.search(header)
    version = version_match.group(1) if version_match else ""
    rows: list[tuple[str, str]] = []
    for lineno, line in enumerate(body.splitlines(), 1):
        line = line.rstrip("\r\n")
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            raise SystemExit(f"line {lineno}: expected text<TAB>code, got {line!r}")
        text_col, code = parts[0], parts[1]
        # ASCII whitespace would break the "code<space>text" line. U+3000
        # (ideographic space, code za in the Sucheng table) is a real glyph.
        if not text_col or any(ch.isascii() and ch.isspace() for ch in text_col):
            raise SystemExit(
                f"line {lineno}: text must be non-empty and contain no ASCII whitespace"
            )
        if not CODE_RE.fullmatch(code):
            raise SystemExit(f"line {lineno}: code must be a-z, got {code!r}")
        rows.append((text_col, code))
    if not rows:
        raise SystemExit("dict yaml body has no rows")
    return version, rows


def load_quick_dict(path: Path) -> tuple[str, list[tuple[str, str]]]:
    return parse_quick_dict(path.read_text(encoding="utf-8"))


def render_cin(rows: list[tuple[str, str]], version: str) -> str:
    version_note = f" (version {version})" if version else ""
    header = [
        "%gen_inp",
        "# Generated by scripts/export_quick_cin.py — do not hand-edit.",
        "# Source: schemas/kinfx-quick/kinfx_quick.dict.yaml" + version_note + ".",
        "# Static Sucheng code table: one %chardef row per dictionary entry.",
        "# Row order follows the dictionary (sort: original).",
        "# Licenses: NOTICE, third_party/rime-quick/LICENSE (LGPL-3.0 upstream:",
        "# rime-quick, rime-cangjie, rime-essay). See licenses/rime-quick-LGPL-3.0.txt.",
        "# This file is only the character table. Mixed English/Chinese input, Lua,",
        "# and association words are not in this table.",
        "# %ename is KINFX-Quick, separate from OpenVanilla's built-in Simplex table.",
        "%ename KINFX-Quick",
        "%cname KINFX速成碼表",
        "%encoding UTF-8",
        "%selkey 123456789",
        "%keyname begin",
        *keyname_lines(),
        "%keyname end",
        "%chardef begin",
    ]
    body = [f"{code} {text}" for text, code in rows]
    lines = header + body + ["%chardef end", ""]
    return "\n".join(lines)


def export_cin(dict_path: Path, out_path: Path) -> int:
    version, rows = load_quick_dict(dict_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    text = render_cin(rows, version)
    with out_path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return len(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dict", type=Path, default=DEFAULT_DICT, dest="dict_path")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    count = export_cin(args.dict_path, args.out)
    print(f"wrote {args.out}: {count} rows from {args.dict_path}")


if __name__ == "__main__":
    main()
